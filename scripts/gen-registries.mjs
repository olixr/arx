#!/usr/bin/env node
/**
 * THE SHELF WRITES ITS OWN LEDGER (foundations polish) — regenerates the
 * def-source modules for the JSON-backed registries. Adding a def file
 * is now: drop the JSON in defs/, run `npm run gen:registries`. The
 * registryAgreement test fails if the ledger and the directory disagree.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
export function generate(dir) {
  const defsDir = join(root, 'packages/content/src', dir, 'defs');
  const files = readdirSync(defsDir).filter((f) => f.endsWith('.json')).sort();
  const names = files.map((f, i) => `d${i}`);
  const body =
    `/* GENERATED by scripts/gen-registries.mjs — do not edit by hand.\n` +
    ` * Run \`npm run gen:registries\` after adding or removing a def file. */\n` +
    files.map((f, i) => `import d${i} from './defs/${f}';`).join('\n') +
    `\n\nexport const SOURCES: readonly unknown[] = [${names.join(', ')}];\n` +
    `export const SOURCE_COUNT = ${files.length};\n`;
  const out = join(root, 'packages/content/src', dir, 'defs.generated.ts');
  const prev = (() => { try { return readFileSync(out, 'utf8'); } catch { return ''; } })();
  if (process.argv.includes('--check')) {
    if (prev !== body) {
      console.error(`STALE ${dir}/defs.generated.ts — run npm run gen:registries`);
      process.exitCode = 1;
    } else {
      console.log(`OK ${dir}: ${files.length} defs`);
    }
    return;
  }
  writeFileSync(out, body);
  console.log(`wrote ${dir}/defs.generated.ts (${files.length} defs)`);
}
generate('actors');
generate('dialogues');
